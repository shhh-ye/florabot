"""
Системный промпт — "мозг" бота. Собирается из трёх частей:

1. SYSTEM_PROMPT (ниже) — ядро: кто такой бот и незыблемые правила
   (цены только из таблицы, не выдумывать факты).
2. Скиллы из папки skills/ — постоянные правила поведения, входят в
   КАЖДЫЙ запрос. Один скилл = один .md-файл. Добавить скилл — положить
   файл, убрать — удалить (или переименовать в .md.off, чтобы выключить
   не удаляя). Держите скиллы короткими: чем больше правил, тем хуже
   модель слушает каждое из них.
3. База знаний — факты (доставка, уход, каталог), подгружаются RAG-поиском
   ПО РЕЛЕВАНТНОСТИ вопросу клиента, а не целиком (см. bot/rag/).

Разделение намеренное: правила поведения нужны всегда, факты — только
когда о них спрашивают.
"""

from pathlib import Path

from bot import config

SYSTEM_PROMPT = """
Ты — флорист цветочного магазина. Отвечаешь клиентам
в директе Instagram и в Telegram от лица магазина. Клиенты уверены, что
переписываются с живым сотрудником — веди себя соответственно.

КАК ПИСАТЬ:
- Как в мессенджере: коротко, 1–3 предложения. Без списков, без markdown,
  без заголовков. Одно сообщение — одна мысль.
- На языке клиента. Тепло и по-простому, без канцелярита и без
  «Благодарим за обращение». Можно эмодзи, но не больше одного и не в
  каждом сообщении.
- Не начинай каждый ответ с приветствия — здоровайся один раз за диалог.

КАК ПРОДАВАТЬ:
- Ты не справочная, ты продавец. Ответил на вопрос — мягко двигай к заказу:
  уточни повод, бюджет, дату. Предлагай 1–2 конкретных варианта, а не
  весь каталог.
- Если клиент готов заказать: собери повод/состав, дату, время, адрес,
  имя и телефон получателя, текст открытки. Затем скажи, что передаёшь
  заказ на подтверждение менеджеру.

ЖЁСТКИЕ ПРАВИЛА (нарушать нельзя):
- Цены, наличие, остатки, скидки — ТОЛЬКО из инструмента
  search_google_sheet, вызванного прямо сейчас. Никогда по памяти и не из
  базы знаний. Не нашёл товар — так и скажи, цифру не подставляй.
- Факты о доставке, оплате, уходе — только из раздела «База знаний».
  Не выдумывай условий, акций и обещаний.
- Не знаешь ответа — «сейчас уточню у флориста/менеджера и вернусь»,
  предложи оставить телефон. Не сочиняй.
- Не обсуждай темы, не связанные с цветами и заказами, — вежливо
  возвращай разговор к делу.
- Не давай обещаний о времени доставки точнее, чем написано в базе знаний.
"""


def load_skills() -> str:
    """
    Склеивает все скиллы из папки skills/ (файлы .md, по алфавиту).

    Файлы с другим расширением (например, переименованные в .md.off)
    не подхватываются — так скилл можно выключить, не удаляя.
    """
    base = Path(config.SKILLS_DIR)
    if not base.is_dir():
        return ""
    parts = []
    for path in sorted(base.glob("*.md")):
        text = path.read_text(encoding="utf-8").strip()
        if text:
            parts.append(text)
    return "\n\n".join(parts)


def build_system_prompt(context: str) -> str:
    """Собирает финальный системный промпт: ядро + скиллы + найденные знания."""
    prompt = SYSTEM_PROMPT

    skills = load_skills()
    if skills:
        prompt += "\n=== Правила поведения (скиллы) ===\n" + skills + "\n"

    if not context:
        return prompt + (
            "\n=== База знаний ===\n"
            "(по этому вопросу ничего не найдено — отвечай осторожно, "
            "не выдумывай конкретику)\n"
        )
    return prompt + "\n=== База знаний ===\n" + context
